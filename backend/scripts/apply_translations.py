print(f"Total keys to inject: {len(expected_keys)}")

for lang, m in all_maps.items():
    missing = expected_keys - set(m.keys())
    extra = set(m.keys()) - expected_keys
    if missing:
        print(f"[{lang}] Missing keys: {len(missing)}: {list(missing)[:5]}")
    if extra:
        print(f"[{lang}] Extra keys: {len(extra)}: {list(extra)[:5]}")
    assert not missing and not extra, f"Parity mismatch in {lang}"

print("All 5 language maps have 100% key parity!")

def set_nested(d, dot_key, value):
    parts = dot_key.split(".")
    curr = d
    for part in parts[:-1]:
        if part not in curr or not isinstance(curr[part], dict):
            curr[part] = {}
        curr = curr[part]
    curr[parts[-1]] = value

# Inject into existing locale files
for lang, m in all_maps.items():
    target_file = locales_dir / f"{lang}.json"
    with open(target_file, "r", encoding="utf-8") as f:
        file_data = json.load(f)
    
    for k, v in m.items():
        set_nested(file_data, k, v)
    
    with open(target_file, "w", encoding="utf-8") as f:
        json.dump(file_data, f, indent=2, ensure_ascii=False)
    print(f"Successfully updated {target_file}")

